`timescale 1ns / 1ps
// emy_buf : physical tensor memories, IMG banks, and the one-active-engine switch.
//
// Four engines expose the common U_201 memory interface as arrays indexed
//   0=VEC, 1=GEMM, 2=DW, 3=SCAN.  active_valid/active_engine select the only
// engine allowed to issue requests.  A/B/X/SKIP/WORK are 64-bit block RAMs,
// ACC is a 64-bit UltraRAM, and IMG is four 64-bit UltraRAM banks read as one
// 256-bit line ([Jae 2026-10-19] IMG ext: lines >= IMG_URAM_LINES live in four block-RAM
// extension banks instead; the line number space is continuous, the engines do not know).  Tensor and IMG reads have exactly two clocks of latency
// ([Jae 2026-10-18] was one: the RAM output register plus a registered
// buffer / owner mux, so the deep BRAM / URAM output muxes get their own
// clock; the engines sample rd*_data / img_data two clocks after *_en).
//
// The response owner and buffer selector are registered with each request, so
// changing active_engine cannot redirect an outstanding response.  The two
// engine read ports may run together only when they select different physical
// tensor buffers.  Same-buffer dual read is illegal and reported in fault[2].
//
// The input ring has a ready/valid write port to WORK.  Engine writes have
// priority and deassert ring_ready.  IMG loading may share a cycle with an IMG
// read at a different line; same-line read/write is blocked and reported.  A
// BUF_OUT engine write is sent to the external output adapter.  BUF_IN is not
// a physical tensor memory in this module.
//
// fault bit meanings:
//   [0] rd0 invalid id/address, [1] rd1 invalid id/address,
//   [2] same-buffer dual read, [3] engine write invalid id/address,
//   [4] ring address out of WORK range,
//   [5] IMG read/load out of range, [6] IMG same-line read/load collision,
//   [7] tensor same-address read/write (unsupported; different addresses work).
import emy_engine_pkg::*;
module emy_buf #(
    // engine_image.py currently measures 169,585 256-bit lines.  Keep this a
    // parameter so integration can use a later regenerated image without
    // changing this module's logic.
    parameter int unsigned IMG_LINES = 198992,
    // [Jae 2026-10-19] IMG ext: lines [0, IMG_URAM_LINES) in the UltraRAM banks, [IMG_URAM_LINES, IMG_LINES) in block-RAM
    // extension banks (plan A: 45 URAM per bank = 184,320 lines + the rest in BRAM; 47/bank = URAM 100 % did not place on xcku19p).  Default = IMG_LINES: no extension.
    parameter int unsigned IMG_URAM_LINES = IMG_LINES
) (
    input  logic clk,
    input  logic nRst,

    input  logic       active_valid,
    input  logic [1:0] active_engine,

    input  logic [3:0]                     eng_rd0_en,
    input  logic [3:0][BUF_ID_W-1:0]       eng_rd0_buf,
    input  logic [3:0][BUF_ADDR_W-1:0]     eng_rd0_addr,
    output logic [3:0][WORD_W-1:0]         eng_rd0_data,
    input  logic [3:0]                     eng_rd1_en,
    input  logic [3:0][BUF_ID_W-1:0]       eng_rd1_buf,
    input  logic [3:0][BUF_ADDR_W-1:0]     eng_rd1_addr,
    output logic [3:0][WORD_W-1:0]         eng_rd1_data,
    input  logic [3:0]                     eng_wr_en,
    input  logic [3:0][BUF_ID_W-1:0]       eng_wr_buf,
    input  logic [3:0][BUF_ADDR_W-1:0]     eng_wr_addr,
    input  logic [3:0][WORD_W-1:0]         eng_wr_data,
    input  logic [3:0][7:0]                eng_wr_be,
    input  logic [3:0]                     eng_img_en,
    input  logic [3:0][IMG_ADDR_W-1:0]     eng_img_addr,
    output logic [3:0][IMG_LINE_W-1:0]     eng_img_data,

    // Boot-loader write port: one 64-bit bank word per accepted transfer.
    input  logic                         img_load_valid,
    output logic                         img_load_ready,
    input  logic [1:0]                   img_load_bank,
    input  logic [IMG_ADDR_W-1:0]        img_load_addr,
    input  logic [WORD_W-1:0]            img_load_data,
    input  logic [7:0]                   img_load_be,

    // Input converter write port into the WORK row ring.
    input  logic                         ring_valid,
    output logic                         ring_ready,
    input  logic [BUF_ADDR_W-1:0]        ring_addr,
    input  logic [WORD_W-1:0]            ring_data,
    input  logic [7:0]                   ring_be,

    // BUF_OUT adapter.  The current contract has no ready on engine writes.
    output logic                         out_wr_en,
    output logic [BUF_ADDR_W-1:0]        out_wr_addr,
    output logic [WORD_W-1:0]            out_wr_data,
    output logic [7:0]                   out_wr_be,

    output logic [7:0]                   fault
);
    // Single source of truth generated by tools/buffer_map.py.  Do not copy
    // these capacities into a second hand-maintained table.
`include "emy_buffer_map_pkg.svh"
    localparam int unsigned A_WORDS    = BUF_A_WORDS;
    localparam int unsigned B_WORDS    = BUF_B_WORDS;
    localparam int unsigned X_WORDS    = BUF_X_WORDS;
    localparam int unsigned SKIP_WORDS = BUF_SKIP_WORDS;
    localparam int unsigned WORK_WORDS = BUF_WORK_WORDS;
    localparam int unsigned ACC_WORDS  = BUF_ACC_WORDS;

    (* ram_style = "block" *) logic [63:0] mem_a    [0:A_WORDS-1];
    (* ram_style = "block" *) logic [63:0] mem_b    [0:B_WORDS-1];
    (* ram_style = "block" *) logic [63:0] mem_x    [0:X_WORDS-1];
    (* ram_style = "block" *) logic [63:0] mem_skip [0:SKIP_WORDS-1];
    (* ram_style = "block" *) logic [63:0] mem_work [0:WORK_WORDS-1];
    (* ram_style = "ultra" *) logic [63:0] mem_acc  [0:ACC_WORDS-1];
    localparam int unsigned IMG_U_LINES  = (IMG_URAM_LINES < IMG_LINES) ? IMG_URAM_LINES : IMG_LINES;
    localparam int unsigned IMG_EXT_LINES = IMG_LINES - IMG_U_LINES;                 // 0 = no extension
    localparam int unsigned IMG_EXT_DEPTH = (IMG_EXT_LINES > 0) ? IMG_EXT_LINES : 1;
    (* ram_style = "ultra" *) logic [63:0] mem_img0 [0:IMG_U_LINES-1];
    (* ram_style = "ultra" *) logic [63:0] mem_img1 [0:IMG_U_LINES-1];
    (* ram_style = "ultra" *) logic [63:0] mem_img2 [0:IMG_U_LINES-1];
    (* ram_style = "ultra" *) logic [63:0] mem_img3 [0:IMG_U_LINES-1];
    (* ram_style = "block" *) logic [63:0] mem_ext0 [0:IMG_EXT_DEPTH-1];           // [Jae 2026-10-19] IMG ext
    (* ram_style = "block" *) logic [63:0] mem_ext1 [0:IMG_EXT_DEPTH-1];
    (* ram_style = "block" *) logic [63:0] mem_ext2 [0:IMG_EXT_DEPTH-1];
    (* ram_style = "block" *) logic [63:0] mem_ext3 [0:IMG_EXT_DEPTH-1];

    logic                         s_rd0_en, s_rd1_en, s_wr_en, s_img_en;
    logic [BUF_ID_W-1:0]          s_rd0_buf, s_rd1_buf, s_wr_buf;
    logic [BUF_ADDR_W-1:0]        s_rd0_addr, s_rd1_addr, s_wr_addr;
    logic [WORD_W-1:0]            s_wr_data;
    logic [7:0]                   s_wr_be;
    logic [IMG_ADDR_W-1:0]        s_img_addr;

    always @(*) begin
        s_rd0_en   = 1'b0; s_rd0_buf  = '0; s_rd0_addr = '0;
        s_rd1_en   = 1'b0; s_rd1_buf  = '0; s_rd1_addr = '0;
        s_wr_en    = 1'b0; s_wr_buf   = '0; s_wr_addr  = '0;
        s_wr_data  = '0;   s_wr_be    = '0;
        s_img_en   = 1'b0; s_img_addr = '0;
        if (active_valid) begin
            s_rd0_en   = eng_rd0_en[active_engine];
            s_rd0_buf  = eng_rd0_buf[active_engine];
            s_rd0_addr = eng_rd0_addr[active_engine];
            s_rd1_en   = eng_rd1_en[active_engine];
            s_rd1_buf  = eng_rd1_buf[active_engine];
            s_rd1_addr = eng_rd1_addr[active_engine];
            s_wr_en    = eng_wr_en[active_engine];
            s_wr_buf   = eng_wr_buf[active_engine];
            s_wr_addr  = eng_wr_addr[active_engine];
            s_wr_data  = eng_wr_data[active_engine];
            s_wr_be    = eng_wr_be[active_engine];
            s_img_en   = eng_img_en[active_engine];
            s_img_addr = eng_img_addr[active_engine];
        end
    end

    function automatic logic tensor_id(input logic [BUF_ID_W-1:0] b);
        tensor_id = (b == BUF_A) || (b == BUF_B) || (b == BUF_X) ||
                    (b == BUF_SKIP) || (b == BUF_WORK) || (b == BUF_ACC);
    endfunction
    function automatic logic addr_ok(input logic [BUF_ID_W-1:0] b,
                                     input logic [BUF_ADDR_W-1:0] a);
        case (b)
            BUF_A:    addr_ok = (a < A_WORDS);
            BUF_B:    addr_ok = (a < B_WORDS);
            BUF_X:    addr_ok = (a < X_WORDS);
            BUF_SKIP: addr_ok = (a < SKIP_WORDS);
            BUF_WORK: addr_ok = (a < WORK_WORDS);
            BUF_ACC:  addr_ok = (a < ACC_WORDS);
            default:  addr_ok = 1'b0;
        endcase
    endfunction

    wire rd0_ok = s_rd0_en && tensor_id(s_rd0_buf) && addr_ok(s_rd0_buf, s_rd0_addr);
    wire rd1_ok0 = s_rd1_en && tensor_id(s_rd1_buf) && addr_ok(s_rd1_buf, s_rd1_addr);
    wire rd_same_buf = rd0_ok && rd1_ok0 && (s_rd0_buf == s_rd1_buf);
    wire rd1_ok = rd1_ok0 && !rd_same_buf; // deterministic illegal-request handling: rd0 wins.
    wire wr_tensor_req = s_wr_en && tensor_id(s_wr_buf);
    wire wr_tensor_ok = wr_tensor_req && addr_ok(s_wr_buf, s_wr_addr);
    wire wr_out_ok = s_wr_en && (s_wr_buf == BUF_OUT);
    wire ring_addr_ok = (ring_addr < WORK_WORDS);
    // A low ready is ordinary backpressure, never a protocol error.  Invalid
    // addresses are not acknowledged; fault[4] provides the diagnostic.
    assign ring_ready = ring_addr_ok && !(wr_tensor_req && (s_wr_buf == BUF_WORK));
    wire ring_fire = ring_valid && ring_ready && ring_addr_ok;
    wire img_read_ok = s_img_en && (s_img_addr < IMG_LINES);
    wire img_load_addr_ok = (img_load_addr < IMG_LINES);
    wire img_same_line = img_load_valid && img_read_ok && (img_load_addr == s_img_addr);
    assign img_load_ready = img_load_addr_ok && !img_same_line;
    wire img_load_fire = img_load_valid && img_load_ready;
    // [Jae 2026-10-19] IMG ext: which store a line lives in (the compare is against a constant; the URAM arrays are never indexed past IMG_U_LINES)
    wire img_rd_ext = (IMG_EXT_LINES != 0) && (s_img_addr >= IMG_ADDR_W'(IMG_U_LINES));
    wire img_ld_ext = (IMG_EXT_LINES != 0) && (img_load_addr >= IMG_ADDR_W'(IMG_U_LINES));
    wire [IMG_ADDR_W-1:0] img_rd_ext_a = s_img_addr   - IMG_ADDR_W'(IMG_U_LINES);
    wire [IMG_ADDR_W-1:0] img_ld_ext_a = img_load_addr - IMG_ADDR_W'(IMG_U_LINES);

    wire rw_same0 = rd0_ok && ((wr_tensor_ok && s_rd0_buf == s_wr_buf && s_rd0_addr == s_wr_addr) ||
                              (ring_fire && s_rd0_buf == BUF_WORK && s_rd0_addr == ring_addr));
    wire rw_same1 = rd1_ok && ((wr_tensor_ok && s_rd1_buf == s_wr_buf && s_rd1_addr == s_wr_addr) ||
                              (ring_fire && s_rd1_buf == BUF_WORK && s_rd1_addr == ring_addr));

    always @(*) begin
        fault = '0;
        fault[0] = s_rd0_en && !rd0_ok;
        fault[1] = s_rd1_en && !rd1_ok0;
        fault[2] = rd_same_buf;
        fault[3] = s_wr_en && !(wr_tensor_ok || wr_out_ok);
        fault[4] = ring_valid && !ring_addr_ok;
        fault[5] = (s_img_en && !img_read_ok) || (img_load_valid && !img_load_addr_ok);
        fault[6] = img_same_line;
        fault[7] = rw_same0 || rw_same1;
    end

    assign out_wr_en   = active_valid && wr_out_ok;
    assign out_wr_addr = s_wr_addr;
    assign out_wr_data = s_wr_data;
    assign out_wr_be   = s_wr_be;

    // One registered read port and one byte-enabled write port per tensor RAM.
    logic a_re, b_re, x_re, skip_re, work_re, acc_re;
    logic [BUF_ADDR_W-1:0] a_ra, b_ra, x_ra, skip_ra, work_ra, acc_ra;
    logic a_we, b_we, x_we, skip_we, work_we, acc_we;
    logic [BUF_ADDR_W-1:0] a_wa, b_wa, x_wa, skip_wa, work_wa, acc_wa;
    logic [63:0] a_wd, b_wd, x_wd, skip_wd, work_wd, acc_wd;
    logic [7:0] a_be, b_be, x_be, skip_be, work_be, acc_be;
    logic [63:0] a_q, b_q, x_q, skip_q, work_q, acc_q;

    always @(*) begin
        a_re=0; b_re=0; x_re=0; skip_re=0; work_re=0; acc_re=0;
        a_ra='0; b_ra='0; x_ra='0; skip_ra='0; work_ra='0; acc_ra='0;
        if (rd0_ok) begin
            case (s_rd0_buf)
                BUF_A: begin a_re=1; a_ra=s_rd0_addr; end
                BUF_B: begin b_re=1; b_ra=s_rd0_addr; end
                BUF_X: begin x_re=1; x_ra=s_rd0_addr; end
                BUF_SKIP: begin skip_re=1; skip_ra=s_rd0_addr; end
                BUF_WORK: begin work_re=1; work_ra=s_rd0_addr; end
                BUF_ACC: begin acc_re=1; acc_ra=s_rd0_addr; end
                default: ;
            endcase
        end
        if (rd1_ok) begin
            case (s_rd1_buf)
                BUF_A: begin a_re=1; a_ra=s_rd1_addr; end
                BUF_B: begin b_re=1; b_ra=s_rd1_addr; end
                BUF_X: begin x_re=1; x_ra=s_rd1_addr; end
                BUF_SKIP: begin skip_re=1; skip_ra=s_rd1_addr; end
                BUF_WORK: begin work_re=1; work_ra=s_rd1_addr; end
                BUF_ACC: begin acc_re=1; acc_ra=s_rd1_addr; end
                default: ;
            endcase
        end

        a_we=0; b_we=0; x_we=0; skip_we=0; work_we=0; acc_we=0;
        a_wa='0; b_wa='0; x_wa='0; skip_wa='0; work_wa='0; acc_wa='0;
        a_wd='0; b_wd='0; x_wd='0; skip_wd='0; work_wd='0; acc_wd='0;
        a_be='0; b_be='0; x_be='0; skip_be='0; work_be='0; acc_be='0;
        if (wr_tensor_ok) begin
            case (s_wr_buf)
                BUF_A: begin a_we=1; a_wa=s_wr_addr; a_wd=s_wr_data; a_be=s_wr_be; end
                BUF_B: begin b_we=1; b_wa=s_wr_addr; b_wd=s_wr_data; b_be=s_wr_be; end
                BUF_X: begin x_we=1; x_wa=s_wr_addr; x_wd=s_wr_data; x_be=s_wr_be; end
                BUF_SKIP: begin skip_we=1; skip_wa=s_wr_addr; skip_wd=s_wr_data; skip_be=s_wr_be; end
                BUF_WORK: begin work_we=1; work_wa=s_wr_addr; work_wd=s_wr_data; work_be=s_wr_be; end
                BUF_ACC: begin acc_we=1; acc_wa=s_wr_addr; acc_wd=s_wr_data; acc_be=s_wr_be; end
                default: ;
            endcase
        end
        // [Jae 2026-10-15] the ring write must not depend on an engine write to ANOTHER buffer: ring_ready already excludes
        // the only real conflict (engine write to WORK), so a ring_fire always lands. (Was `else if`: every ring word that
        // coincided with an engine write to X / ACC / B was dropped although the handshake had completed.)
        if (ring_fire) begin
            work_we=1; work_wa=ring_addr; work_wd=ring_data; work_be=ring_be;
        end
    end

`define EMY_RAM_PROC(NAME) \
    always @(posedge clk) begin \
        if (NAME``_re) NAME``_q <= #1 mem_``NAME[NAME``_ra]; \
        if (NAME``_we) for (int by = 0; by < 8; by++) \
            if (NAME``_be[by]) mem_``NAME[NAME``_wa][8*by +: 8] <= #1 NAME``_wd[8*by +: 8]; \
    end
    `EMY_RAM_PROC(a)
    `EMY_RAM_PROC(b)
    `EMY_RAM_PROC(x)
    `EMY_RAM_PROC(skip)
    `EMY_RAM_PROC(work)
    `EMY_RAM_PROC(acc)
`undef EMY_RAM_PROC

    logic rd0_v_q, rd1_v_q;
    logic [1:0] rd0_owner_q, rd1_owner_q;
    logic [BUF_ID_W-1:0] rd0_buf_q, rd1_buf_q;
    always @(posedge clk) begin
        if (!nRst) begin
            rd0_v_q <= #1 1'b0; rd1_v_q <= #1 1'b0;
            rd0_owner_q <= #1 '0; rd1_owner_q <= #1 '0;
            rd0_buf_q <= #1 '0; rd1_buf_q <= #1 '0;
        end else begin
            rd0_v_q <= #1 rd0_ok;
            rd1_v_q <= #1 rd1_ok;
            if (rd0_ok) begin rd0_owner_q <= #1 active_engine; rd0_buf_q <= #1 s_rd0_buf; end
            if (rd1_ok) begin rd1_owner_q <= #1 active_engine; rd1_buf_q <= #1 s_rd1_buf; end
        end
    end

    // [Jae 2026-10-18] read latency 2: the buffer / owner mux is registered (eng_rd*_data = rd*_mux one clock later).
    logic [3:0][WORD_W-1:0] rd0_mux, rd1_mux;
    always @(*) begin
        rd0_mux = '0;
        rd1_mux = '0;
        // Keep the RAM q signals explicit in this block.  Some synthesis and
        // simulation tools omit globals referenced only inside a function
        // from an always @(*) sensitivity set, which would freeze a streaming
        // response after its first word.
        if (rd0_v_q) begin
            case (rd0_buf_q)
                BUF_A:    rd0_mux[rd0_owner_q] = a_q;
                BUF_B:    rd0_mux[rd0_owner_q] = b_q;
                BUF_X:    rd0_mux[rd0_owner_q] = x_q;
                BUF_SKIP: rd0_mux[rd0_owner_q] = skip_q;
                BUF_WORK: rd0_mux[rd0_owner_q] = work_q;
                BUF_ACC:  rd0_mux[rd0_owner_q] = acc_q;
                default:  rd0_mux[rd0_owner_q] = '0;
            endcase
        end
        if (rd1_v_q) begin
            case (rd1_buf_q)
                BUF_A:    rd1_mux[rd1_owner_q] = a_q;
                BUF_B:    rd1_mux[rd1_owner_q] = b_q;
                BUF_X:    rd1_mux[rd1_owner_q] = x_q;
                BUF_SKIP: rd1_mux[rd1_owner_q] = skip_q;
                BUF_WORK: rd1_mux[rd1_owner_q] = work_q;
                BUF_ACC:  rd1_mux[rd1_owner_q] = acc_q;
                default:  rd1_mux[rd1_owner_q] = '0;
            endcase
        end
    end

    always @(posedge clk) begin
        eng_rd0_data <= #1 rd0_mux;
        eng_rd1_data <= #1 rd1_mux;
    end

    // IMG: four registered reads form one line.  Loader writes one selected bank.
    logic [63:0] img0_q, img1_q, img2_q, img3_q;
    logic [63:0] ext0_q, ext1_q, ext2_q, ext3_q;                                   // [Jae 2026-10-19] IMG ext
    logic        img_sel_q;                                                        // 1 = the registered line came from the extension
    always @(posedge clk) begin
        if (img_read_ok && !img_rd_ext) begin
            img0_q <= #1 mem_img0[s_img_addr]; img1_q <= #1 mem_img1[s_img_addr];
            img2_q <= #1 mem_img2[s_img_addr]; img3_q <= #1 mem_img3[s_img_addr];
        end
        if (img_read_ok && img_rd_ext) begin
            ext0_q <= #1 mem_ext0[img_rd_ext_a]; ext1_q <= #1 mem_ext1[img_rd_ext_a];
            ext2_q <= #1 mem_ext2[img_rd_ext_a]; ext3_q <= #1 mem_ext3[img_rd_ext_a];
        end
        if (img_read_ok) img_sel_q <= #1 img_rd_ext;
        if (img_load_fire && !img_ld_ext) begin
            case (img_load_bank)
                2'd0: for (int by=0; by<8; by++) if (img_load_be[by]) mem_img0[img_load_addr][8*by +: 8] <= #1 img_load_data[8*by +: 8];
                2'd1: for (int by=0; by<8; by++) if (img_load_be[by]) mem_img1[img_load_addr][8*by +: 8] <= #1 img_load_data[8*by +: 8];
                2'd2: for (int by=0; by<8; by++) if (img_load_be[by]) mem_img2[img_load_addr][8*by +: 8] <= #1 img_load_data[8*by +: 8];
                2'd3: for (int by=0; by<8; by++) if (img_load_be[by]) mem_img3[img_load_addr][8*by +: 8] <= #1 img_load_data[8*by +: 8];
            endcase
        end
        if (img_load_fire && img_ld_ext) begin
            case (img_load_bank)
                2'd0: for (int by=0; by<8; by++) if (img_load_be[by]) mem_ext0[img_ld_ext_a][8*by +: 8] <= #1 img_load_data[8*by +: 8];
                2'd1: for (int by=0; by<8; by++) if (img_load_be[by]) mem_ext1[img_ld_ext_a][8*by +: 8] <= #1 img_load_data[8*by +: 8];
                2'd2: for (int by=0; by<8; by++) if (img_load_be[by]) mem_ext2[img_ld_ext_a][8*by +: 8] <= #1 img_load_data[8*by +: 8];
                2'd3: for (int by=0; by<8; by++) if (img_load_be[by]) mem_ext3[img_ld_ext_a][8*by +: 8] <= #1 img_load_data[8*by +: 8];
            endcase
        end
    end
    logic img_v_q;
    logic [1:0] img_owner_q;
    always @(posedge clk) begin
        if (!nRst) begin img_v_q <= #1 1'b0; img_owner_q <= #1 '0; end
        else begin
            img_v_q <= #1 img_read_ok;
            if (img_read_ok) img_owner_q <= #1 active_engine;
        end
    end
    logic [3:0][IMG_LINE_W-1:0] img_mux;
    always @(*) begin
        img_mux = '0;
        if (img_v_q) img_mux[img_owner_q] = img_sel_q ? {ext3_q, ext2_q, ext1_q, ext0_q} : {img3_q, img2_q, img1_q, img0_q};   // [Jae 2026-10-19] IMG ext
    end
    always @(posedge clk) eng_img_data <= #1 img_mux;      // [Jae 2026-10-18] IMG read latency 2

