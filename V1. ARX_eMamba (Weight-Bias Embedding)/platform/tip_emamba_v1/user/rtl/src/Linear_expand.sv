) matMult_20 (
    .dIn(matMult_dIn),
    .weight(matMult_weight),
    .bias(matMult_bias),

    .dOut(matMult_dOut)
);

shifter_right #(
    .DATA_WIDTH(DATA_WIDTH_DOUT),
    .NUM_SHIFT(NUM_RSH_DOUT)
) shifter_right (
    .dIn(matMult_dOut),
    .dOut(matMult_dOut_shifted)
);

saturator #(
    .DATA_WIDTH(DATA_WIDTH_DOUT_RSH)
) saturator_dOut (
    .dIn(matMult_dOut_shifted),
    .dOut(matMult_dOut_saturated)
);

// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
// Main Code
// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
// FSM
always @(posedge clk) begin
    if (!nRst || ps_start)
        curr_state <= #1 INIT;
    else
        curr_state <= #1 next_state;
end

always @(*) begin
    next_state = curr_state;

    case (curr_state)
        INIT, IDLE: begin
            if (prev_layer_ready & next_layer_ready)
                next_state = COMPUTING;
            else
                next_state = curr_state;
        end

        COMPUTING: begin
            if (curr_weight_column == NUM_DIM_2-1)
                next_state = IDLE;
            else
                next_state = curr_state;
        end

        default: next_state = curr_state;
    endcase
end

// Compute cycle
always @(posedge clk) begin
    if (!nRst) begin
        curr_dIn_row        <= #1 'd0;
        curr_weight_column  <= #1 'd0;
    end else begin
        curr_dIn_row        <= #1 next_dIn_row;
        curr_weight_column  <= #1 next_weight_column;
    end
end

always @(*) begin
    next_dIn_row        = curr_dIn_row;
    next_weight_column  = curr_weight_column;
    
    case (curr_state)
        INIT: begin
            next_dIn_row        = 0;
            next_weight_column  = 0;
        end

        COMPUTING: begin
            if (curr_weight_column < NUM_DIM_2-1) begin
                next_dIn_row        = curr_dIn_row;
                next_weight_column  = curr_weight_column + 1;
            end else begin
                next_dIn_row        = curr_dIn_row + 1;
                next_weight_column  = 0;
            end
        end

        default: begin
            next_dIn_row        = curr_dIn_row;
            next_weight_column  = curr_weight_column;
        end
    endcase
end

// Matrix multiplier data
always @(*) begin
    matMult_dIn     = dIn_mem;
    matMult_weight  = weight[curr_weight_column];
    matMult_bias    = bias[curr_weight_column];
end

// Final output
always @(posedge clk) begin
    if (!nRst)
        for (i = 0; i < NUM_DIM_2; i = i + 1)
            dOut[i] <= #1 'd0;
    else
        if (curr_state == COMPUTING)
            dOut[curr_weight_column] <= #1 matMult_dOut_saturated;
        else
            dOut <= #1 dOut;
end

// Input FF
always @(posedge clk) begin
    if (prev_layer_ready && next_layer_ready && (curr_state == INIT || curr_state == IDLE))
        dIn_mem <= #1 dIn;
    else
        dIn_mem <= #1 dIn_mem;
end

