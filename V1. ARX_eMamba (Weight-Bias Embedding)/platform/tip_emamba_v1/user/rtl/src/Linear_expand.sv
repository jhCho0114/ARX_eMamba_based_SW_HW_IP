logic signed [DATA_WIDTH-1:0] bias      [0:NUM_DIM_2-1];                // 40

logic [1:0] curr_state,
            next_state;

logic [3:0] curr_dIn_row,
            next_dIn_row;

logic [5:0] curr_weight_column,
            next_weight_column;

logic signed [DATA_WIDTH-1:0] matMult_dIn    [0:NUM_DIM_1-1];
logic signed [DATA_WIDTH-1:0] matMult_weight [0:NUM_DIM_1-1];
logic signed [DATA_WIDTH-1:0] matMult_bias;
logic signed [DATA_WIDTH_DOUT-1:0] matMult_dOut;
logic signed [DATA_WIDTH_DOUT_RSH-1:0] matMult_dOut_shifted;
logic signed [DATA_WIDTH-1:0] matMult_dOut_saturated;

logic signed [DATA_WIDTH-1:0] dIn_mem [0:NUM_DIM_1-1];

integer i;

// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
// Submodules
// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
matMult_20 #(
    .DATA_WIDTH(DATA_WIDTH),
