    parameter integer NUM_SCALE_WEIGHT = 8,
    parameter integer NUM_SCALE_BIAS   = 9,
    parameter integer NUM_SCALE_DOUT   = 5,

    // 0: 1st MAMBA, 1: 2nd MAMBA
    parameter integer LAYER_ID = 0
)(
    clk,
    nRst,

    ps_start,

    dIn,
    dOut,

    prev_layer_ready,
    next_layer_ready,
    layer_ready,
    dOut_ready
