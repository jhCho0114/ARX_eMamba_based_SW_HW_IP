// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
// I/O Ports
// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
input clk, nRst;

input ps_start;

input   logic signed [DATA_WIDTH-1:0] dIn   [0:NUM_DIM-1]; // 16x40
output  logic signed [DATA_WIDTH-1:0] dOut  [0:NUM_DIM-1]; // 1x40

input   prev_layer_ready, next_layer_ready;
output  layer_ready, dOut_ready;

// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
// Internal Variables
// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
logic signed [DATA_WIDTH-1:0] weight    [0:NUM_DIM-1][0:NUM_DIM-1]; // 40x40
logic signed [DATA_WIDTH-1:0] bias      [0:NUM_DIM-1]; // 40

logic [1:0] curr_state,
            next_state;

logic [3:0] curr_dIn_row,
            next_dIn_row;

logic [5:0] curr_weight_column,
            next_weight_column;

logic signed [DATA_WIDTH-1:0] matMult_dIn    [0:NUM_DIM-1];
logic signed [DATA_WIDTH-1:0] matMult_weight [0:NUM_DIM-1];
logic signed [DATA_WIDTH-1:0] matMult_bias;
logic signed [DATA_WIDTH-1:0] matMult_dOut;

logic signed [DATA_WIDTH-1:0] dIn_mem [0:NUM_DIM-1];

