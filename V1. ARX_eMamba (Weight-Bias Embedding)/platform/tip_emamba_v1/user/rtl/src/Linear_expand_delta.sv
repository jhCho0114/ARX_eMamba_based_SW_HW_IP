input ps_start;

input   logic signed [DATA_WIDTH-1:0] dIn   [0:NUM_DIM_1-1]; // 1x32
output  logic signed [DATA_WIDTH-1:0] dOut  [0:NUM_DIM_2-1]; // 1x40

input   prev_layer_ready, next_layer_ready;
output  layer_ready, dOut_ready;

// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
// Internal Variables
// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
