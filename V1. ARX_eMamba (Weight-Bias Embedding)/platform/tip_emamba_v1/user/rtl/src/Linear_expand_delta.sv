module Linear_expand_delta #(
    parameter integer DATA_WIDTH = 8,
    parameter integer NUM_SEQLEN = 16,
    parameter integer NUM_DIM_1  = 32,
    parameter integer NUM_DIM_2  = 40,

    parameter integer NUM_SCALE_DIN    = 6,
    parameter integer NUM_SCALE_WEIGHT = 8,
    parameter integer NUM_SCALE_BIAS   = 8,
    parameter integer NUM_SCALE_DOUT   = 4,

    // 0: 1st MAMBA, 1: 2nd MAMBA
    parameter integer LAYER_ID = 0
)(
    clk,
    nRst,

    ps_start,

    dIn,
    dOut,

    prev_layer_ready,
    next_layer_ready,
    layer_ready,
    dOut_ready
);

// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
// Local Parameters
// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
// 4 < log2 32 == 5
localparam DATA_WIDTH_DOUT = DATA_WIDTH*2 + 5;

localparam INIT         = 'd0,
           IDLE         = 'd1,
           COMPUTING    = 'd2;

localparam integer NUM_RSH_DOUT = NUM_SCALE_DIN + NUM_SCALE_WEIGHT - NUM_SCALE_DOUT;
localparam integer DATA_WIDTH_DOUT_8_BIT = DATA_WIDTH_DOUT - NUM_RSH_DOUT;

// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
// I/O Ports
// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
