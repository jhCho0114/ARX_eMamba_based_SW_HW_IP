module shifter_right #(
    parameter integer DATA_WIDTH = 8,
    parameter integer NUM_SHIFT  = 5
)(
    dIn,
    dOut
);

// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
// Local Parameters
// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
localparam integer DATA_WIDTH_DOUT = DATA_WIDTH - NUM_SHIFT;

// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
// I/O Ports
// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
input logic [DATA_WIDTH-1:0] dIn;
output logic [DATA_WIDTH_DOUT-1:0] dOut;

// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
// Internal Variables
// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
logic lsb;

// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
// Main Code
// ========== ========== ========== ========== ========== ========== ========== ========== ========== ==========
assign lsb = dIn[NUM_SHIFT-1];

always @(*) begin
    if (lsb)
        dOut = (dIn >>> NUM_SHIFT) + 1;
    else
        dOut = dIn >>> NUM_SHIFT;
end

endmodule